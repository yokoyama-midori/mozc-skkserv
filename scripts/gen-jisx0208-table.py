"""Generates overlay/mozc_inproc/jisx0208_table.h: the JIS X 0208 -> Unicode table.

The table comes from the euc_jp codec of Python (the standard JIS mapping, for
example "A1 C1" is U+301C WAVE DASH). Rows 1-8 and 16-84 are the characters of
JIS X 0208 (6,879 characters). Rows 9-15 and 85-94 are not used.

usage: python scripts/gen-jisx0208-table.py
"""
import pathlib
import sys

ROWS = 84  # rows 1..84 are stored (rows 9..15 stay 0)
COLS = 94

repo = pathlib.Path(__file__).resolve().parent.parent
target = repo / "overlay" / "mozc_inproc" / "jisx0208_table.h"

count = 0
lines = []
for row in range(1, ROWS + 1):
    values = []
    for col in range(1, COLS + 1):
        value = 0
        if row <= 8 or 16 <= row <= 84:
            try:
                text = bytes([0xA0 + row, 0xA0 + col]).decode("euc_jp")
            except UnicodeDecodeError:
                text = ""
            if len(text) == 1 and ord(text) < 0x10000:
                value = ord(text)
                count += 1
        values.append(f"0x{value:04X}")
    lines.append(f"    // row {row}\n    " + ", ".join(values) + ",")

if count != 6879:
    sys.exit(f"expected 6879 characters, got {count}")

header = f"""// Copyright (c) 2026 mozc-skkserv contributors. BSD-3-Clause (see LICENSE).
//
// JIS X 0208 -> Unicode, indexed by [row - 1][column - 1]. 0 means that the
// cell has no character. {count} characters (rows 1-8 and 16-84).
//
// Generated by scripts/gen-jisx0208-table.py from the euc_jp codec of Python.
// Do not edit by hand.
#ifndef MOZC_SKKSERV_JISX0208_TABLE_H_
#define MOZC_SKKSERV_JISX0208_TABLE_H_

#include <cstdint>

namespace mozc::skkserv {{

inline constexpr int kJisX0208Rows = {ROWS};
inline constexpr int kJisX0208Columns = {COLS};

// clang-format off
inline constexpr uint16_t kJisX0208[kJisX0208Rows][kJisX0208Columns] = {{
{chr(10).join("  {" + chr(10) + l + chr(10) + "  }," for l in lines)}
}};
// clang-format on

}}  // namespace mozc::skkserv

#endif  // MOZC_SKKSERV_JISX0208_TABLE_H_
"""
target.write_text(header, encoding="utf-8", newline="\n")
print(f"wrote {target} ({count} characters)")
